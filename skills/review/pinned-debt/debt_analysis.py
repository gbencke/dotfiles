#!/usr/bin/env python3
"""Measure technical-debt signals for git repositories.

Runs inside the pinned-debt bwrap sandbox; PINNED_DEBT_STORE points at the
pinned tools. For each repo: size, cognitive complexity per function
(sonarjs for JS/TS, complexipy for Python), duplication (jscpd), change
amplification and hotspots (git history). Writes <out>/<repo>.md,
<repo>.json and summary.md.

usage: debt_analysis.py --out DIR [--since '12 months ago'] REPO [REPO...]
       debt_analysis.py --self-test
"""

import argparse
import datetime
import json
import os
import re
import subprocess
import sys
import tempfile
from collections import Counter
from pathlib import Path

def store():
    path = os.environ.get("PINNED_DEBT_STORE")
    if not path:
        raise RuntimeError("PINNED_DEBT_STORE unset: run via pinned-debt")
    return Path(path)

JS_EXT = {".ts", ".tsx", ".mts", ".cts", ".js", ".jsx", ".mjs", ".cjs"}
PY_EXT = {".py"}
GENERATED = re.compile(
    r"(^|/)(node_modules|dist|build|coverage|cdk\.out|\.next|out|vendor"
    r"|__generated__|generated|\.venv|venv)/|\.d\.ts$|\.min\.js$"
)
TEST = re.compile(
    r"(^|/)(__tests__|__mocks__|tests?|cypress|e2e|mocks?)/"
    r"|[._-](test|spec|stories)\.[^/]+$|(^|/)test_[^/]+\.py$"
    r"|_test\.py$|(^|/)conftest\.py$"
)
SONAR_MSG = re.compile(r"Cognitive Complexity from (\d+)")
GENERATED_HEADER = re.compile(
    r"automatically generated|auto[- ]generated|@generated|code generated by"
    r"|do not edit",
    re.IGNORECASE,
)
SUPPRESSION = re.compile(
    r"eslint-disable|@ts-ignore|@ts-expect-error|@ts-nocheck"
    r"|#\s*noqa|#\s*type:\s*ignore|pylint:\s*disable"
)
COGNITIVE_LIMIT = 15  # SonarSource default per function
FILE_LIMIT = 300  # non-blank lines
WIDE_COMMIT = 10  # code files touched by one commit


def run(cmd, cwd, check=True):
    result = subprocess.run(
        cmd, cwd=cwd, capture_output=True, text=True, check=False
    )
    if check and result.returncode != 0:
        raise RuntimeError(
            f"{' '.join(map(str, cmd[:3]))} failed in {cwd}: "
            f"{result.stderr.strip()[-500:]}"
        )
    return result


def pct(values, p):
    """Nearest-rank percentile; 0 for an empty list."""
    if not values:
        return 0
    ordered = sorted(values)
    return ordered[min(len(ordered) - 1, int(p / 100 * len(ordered)))]


def is_code(path):
    return Path(path).suffix in JS_EXT | PY_EXT and not GENERATED.search(path)


def has_generated_header(path):
    with path.open(errors="replace") as handle:
        return bool(GENERATED_HEADER.search(handle.read(400)))


def list_files(repo):
    """Return (prod, tests, generated) code files tracked by git."""
    out = run(["git", "ls-files"], repo).stdout.splitlines()
    code = [f for f in out if is_code(f) and (repo / f).is_file()]
    generated = [f for f in code if has_generated_header(repo / f)]
    skip = set(generated)
    code = [f for f in code if f not in skip]
    prod = [f for f in code if not TEST.search(f)]
    tests = [f for f in code if TEST.search(f)]
    return prod, tests, generated


def count_loc(repo, files):
    def loc(name):
        text = (repo / name).read_text(errors="replace")
        return sum(1 for line in text.splitlines() if line.strip())

    return {name: loc(name) for name in files}


def count_suppressions(repo, files):
    return sum(
        len(SUPPRESSION.findall((repo / name).read_text(errors="replace")))
        for name in files
    )


def parse_eslint_json(output, repo):
    """Return ([(file, line, score)], parse_errors) from mixed output."""
    line = next((x for x in output.splitlines() if x.startswith("[")), None)
    if line is None:
        raise RuntimeError(f"no ESLint JSON in output: {output[-500:]}")
    scores, parse_errors = [], 0
    for result in json.loads(line):
        name = str(Path(result["filePath"]).relative_to(repo))
        for message in result["messages"]:
            if message.get("fatal"):
                parse_errors += 1
                continue
            match = SONAR_MSG.search(message["message"])
            if match:
                scores.append((name, message["line"], int(match.group(1))))
    return scores, parse_errors


def js_cognitive(repo, files):
    if not files:
        return [], 0
    cmd = [
        "node", str(store() / "node_modules/eslint/bin/eslint.js"),
        "--config", str(store() / "config/eslint.debt.config.mjs"),
        "--format", "json", "--no-warn-ignored", "--no-inline-config",
        *files,
    ]
    result = run(cmd, repo, check=False)
    return parse_eslint_json(result.stdout, repo)


def py_cognitive(repo, files):
    if not files:
        return []
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "complexipy.json"
        cmd = [
            str(store() / "py/bin/complexipy"), *files,
            "--output-format", "json", "--output", str(report),
            "--cache-dir", tmp, "-q", "-i",
        ]
        run(cmd, repo, check=False)
        if not report.exists():
            raise RuntimeError(f"complexipy wrote no report in {repo}")
        rows = json.loads(report.read_text())
    return [
        (row["path"], row["function_name"], row["complexity"])
        for row in rows
        if row["complexity"] > 0
    ]


def duplication(repo, files):
    if not files:
        return {"percentage": 0.0, "lines": 0, "clones": []}
    with tempfile.TemporaryDirectory() as tmp:
        cmd = [
            "node", str(store() / "node_modules/jscpd/bin/jscpd"),
            "--silent", "--reporters", "json",
            "--output", tmp, "--min-tokens", "50", "--max-lines", "100000",
            "--max-size", "5mb", *files,
        ]
        run(cmd, repo, check=False)
        report = Path(tmp) / "jscpd-report.json"
        if not report.exists():
            raise RuntimeError(f"jscpd wrote no report in {repo}")
        data = json.loads(report.read_text())
    total = data["statistics"]["total"]
    clones = sorted(
        (
            (c["lines"], c["firstFile"]["name"], c["firstFile"]["start"],
             c["secondFile"]["name"], c["secondFile"]["start"])
            for c in data["duplicates"]
        ),
        reverse=True,
    )
    return {
        "percentage": total["percentage"],
        "lines": total["duplicatedLines"],
        "clones": clones[:10],
    }


def history(repo, since):
    """Return (commits per prod file, code files per commit)."""
    out = run(
        ["git", "log", "--no-merges", f"--since={since}",
         "--format=tformat:@@commit", "--name-only"],
        repo,
    ).stdout
    churn, widths = Counter(), []
    for block in out.split("@@commit")[1:]:
        touched = {f for f in block.split() if is_code(f)}
        if touched:
            widths.append(len(touched))
            churn.update(f for f in touched if not TEST.search(f))
    return churn, widths


def analyse(repo, since):
    prod, tests, generated = list_files(repo)
    loc = count_loc(repo, prod)
    test_loc = count_loc(repo, tests)
    generated_loc = count_loc(repo, generated)
    js = [f for f in prod if Path(f).suffix in JS_EXT]
    py = [f for f in prod if Path(f).suffix in PY_EXT]
    js_scores, parse_errors = js_cognitive(repo, js)
    functions = js_scores + py_cognitive(repo, py)
    per_file = Counter()
    for name, _, score in functions:
        per_file[name] += score
    scores = [score for *_, score in functions]
    churn, widths = history(repo, since)
    prod_loc = sum(loc.values())
    hotspots = sorted(
        (
            (churn[f] * per_file[f], f, loc[f], per_file[f], churn[f])
            for f in prod
            if churn[f] and per_file[f]
        ),
        reverse=True,
    )
    return {
        "repo": repo.name,
        "since": since,
        "prod_files": len(prod),
        "prod_loc": prod_loc,
        "test_loc": sum(test_loc.values()),
        "generated_files": len(generated),
        "generated_loc": sum(generated_loc.values()),
        "parse_errors": parse_errors,
        "suppressions": count_suppressions(repo, prod),
        "functions_scored": len(scores),
        "cognitive_total": sum(scores),
        "cognitive_per_100_loc": round(100 * sum(scores) / prod_loc, 1)
        if prod_loc else 0,
        "cognitive_p90": pct(scores, 90),
        "cognitive_max": max(scores, default=0),
        "functions_over_limit": sum(s > COGNITIVE_LIMIT for s in scores),
        "files_over_limit": sum(n > FILE_LIMIT for n in loc.values()),
        "largest_files": sorted(
            ((n, f) for f, n in loc.items()), reverse=True
        )[:10],
        "worst_functions": sorted(
            functions, key=lambda row: row[2], reverse=True
        )[:15],
        "duplication": duplication(repo, prod),
        "commits": len(widths),
        "files_per_commit_median": pct(widths, 50),
        "files_per_commit_p90": pct(widths, 90),
        "wide_commits_pct": round(
            100 * sum(w >= WIDE_COMMIT for w in widths) / len(widths), 1
        ) if widths else 0,
        "hotspots": hotspots[:15],
    }


def table(header, rows):
    lines = ["| " + " | ".join(header) + " |",
             "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(map(str, row)) + " |" for row in rows]
    return "\n".join(lines)


def render_repo(m):
    dup = m["duplication"]
    sections = [
        f"# Technical debt: {m['repo']}",
        f"Generated {datetime.date.today()}. Production code only "
        f"(tests and generated files excluded). History since "
        f"{m['since']}.",
        "## Summary",
        table(["Metric", "Value"], [
            ("Production files / LOC", f"{m['prod_files']} / {m['prod_loc']}"),
            ("Test LOC", m["test_loc"]),
            ("Generated files / LOC (excluded)",
             f"{m['generated_files']} / {m['generated_loc']}"),
            ("Cognitive complexity per 100 LOC",
             m["cognitive_per_100_loc"]),
            ("Functions scored (>0) / p90 / max",
             f"{m['functions_scored']} / {m['cognitive_p90']} / "
             f"{m['cognitive_max']}"),
            (f"Functions over {COGNITIVE_LIMIT}", m["functions_over_limit"]),
            (f"Files over {FILE_LIMIT} LOC", m["files_over_limit"]),
            ("Duplicated lines", f"{dup['lines']} ({dup['percentage']}%)"),
            ("Commits touching code", m["commits"]),
            ("Code files per commit, median / p90",
             f"{m['files_per_commit_median']} / "
             f"{m['files_per_commit_p90']}"),
            (f"Commits touching {WIDE_COMMIT}+ code files",
             f"{m['wide_commits_pct']}%"),
            ("Lint/type suppressions (eslint-disable, ts-ignore, noqa...)",
             m["suppressions"]),
            ("Files ESLint could not parse", m["parse_errors"]),
        ]),
        "## Hotspots (commits x file cognitive complexity)",
        table(["Score", "File", "LOC", "Cognitive", "Commits"],
              m["hotspots"]) if m["hotspots"] else "None in window.",
        "## Most complex functions",
        table(["File", "Line / function", "Cognitive"],
              m["worst_functions"]),
        "## Largest files",
        table(["LOC", "File"], m["largest_files"]),
        "## Largest clones",
        table(["Lines", "File A", "Line", "File B", "Line"], dup["clones"])
        if dup["clones"] else "None.",
    ]
    return "\n\n".join(sections) + "\n"


def render_summary(results, failed):
    header = ["Repo", "Prod LOC", "Cog/100 LOC", "Fn > 15", "Max fn",
              "Files > 300", "Dup %", "Suppressions", "Files/commit p90", "Wide commits %"]
    rows = [
        (m["repo"], m["prod_loc"], m["cognitive_per_100_loc"],
         m["functions_over_limit"], m["cognitive_max"], m["files_over_limit"],
         m["duplication"]["percentage"], m["suppressions"],
         m["files_per_commit_p90"],
         m["wide_commits_pct"])
        for m in sorted(results, key=lambda r: -r["cognitive_per_100_loc"])
    ]
    return (f"# Technical debt summary ({datetime.date.today()})\n\n"
            + table(header, rows) + failed_note(failed) + "\n")


def failed_note(failed):
    if not failed:
        return ""
    return "\n\nFailed: " + "; ".join(f"{n}: {e}" for n, e in failed)


def self_test():
    assert TEST.search("src/__tests__/a.ts")
    assert TEST.search("src/a.test.tsx") and TEST.search("tests/test_x.py")
    assert not TEST.search("src/testing-utils.ts")
    assert not is_code("dist/a.js") and not is_code("src/a.d.ts")
    assert is_code("src/a.tsx") and not is_code("README.md")
    assert GENERATED_HEADER.search("// This file was automatically generated")
    assert not GENERATED_HEADER.search("// build the generator config")
    assert len(SUPPRESSION.findall("x  # noqa: C901\n// @ts-ignore")) == 2
    assert pct([], 90) == 0 and pct([1, 2, 3, 4], 50) == 3
    repo = Path("/r")
    out = ("warning: noise\n" + json.dumps([{
        "filePath": "/r/src/a.ts",
        "messages": [
            {"line": 4, "message": "Refactor this function to reduce its "
             "Cognitive Complexity from 23 to the 0 allowed."},
            {"fatal": True, "line": 1, "message": "Parsing error"},
        ],
    }]))
    assert parse_eslint_json(out, repo) == ([("src/a.ts", 4, 23)], 1)
    print("self-test ok")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("repos", nargs="*", type=Path)
    parser.add_argument("--out", type=Path, required=False)
    parser.add_argument("--since", default="12 months ago")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    if args.self_test:
        return self_test()
    if not args.repos or not args.out:
        parser.error("give --out and at least one repo")
    args.out.mkdir(parents=True, exist_ok=True)
    results, failed = [], []
    for repo in (r.resolve() for r in args.repos):
        print(f">> {repo.name}", file=sys.stderr, flush=True)
        try:
            metrics = analyse(repo, args.since)
        except (RuntimeError, OSError, ValueError) as error:
            print(f"!! {repo.name}: {error}", file=sys.stderr, flush=True)
            failed.append((repo.name, str(error)[:200]))
            continue
        results.append(metrics)
        (args.out / f"{repo.name}.json").write_text(
            json.dumps(metrics, indent=2))
        (args.out / f"{repo.name}.md").write_text(render_repo(metrics))
    (args.out / "summary.md").write_text(render_summary(results, failed))
    print(args.out / "summary.md")
    return 1 if failed else None


if __name__ == "__main__":
    sys.exit(main())
